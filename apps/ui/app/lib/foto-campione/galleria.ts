import { canonicalJson } from '@taucad/utils/hash';
import { improntaFoto, materialeNormale } from '#lib/foto-campione/impronta.js';
import type { LivelloFoto, MaterialeFoto } from '#lib/foto-campione/impronta.js';
import type { VistaFoto } from '#lib/foto-campione/mappe.js';

/**
 * The gallery of the sample photos (SinopiaCAD D6): which photo stands for each view × material × level, and whether it
 * still shows the model on screen. A photo is «pronta» while its fingerprint equals the one the current model would
 * give it, «da rifare» (grey) as soon as a parameter or the source changes: marked, never regenerated by itself.
 */

/** A photo of the sample, as Sinopia keeps it (`assets` `ai_render` with the CAD's metadata). */
export type FotoCampione = Readonly<{
  /** The Sinopia asset id. */
  id: string;
  vista: VistaFoto;
  materiale: MaterialeFoto;
  livello: LivelloFoto;
  impronta: string;
  /** Milliseconds since the epoch. */
  creata: number;
  /** Where the bytes are: Sinopia storage, or (in the development trial) a local URL. */
  sorgente: Readonly<{ tipo: 'storage'; bucket: string; path: string }> | Readonly<{ tipo: 'url'; url: string }>;
  /** The AI Act label Sinopia wrote. */
  aiAct?: string;
}>;

export type StatoFoto = 'pronta' | 'da-rifare';

/** One slot of the gallery: one view, one material (with its finish), one level. */
export const chiaveFoto = (
  foto: Readonly<{ vista: VistaFoto; materiale: MaterialeFoto; livello: LivelloFoto }>,
): string => canonicalJson([foto.vista, materialeNormale(foto.materiale), foto.livello]);

/**
 * The newest photo of each slot, newest first: a regenerated photo replaces the old one in the gallery (the old one
 * stays in the Sinopia project).
 *
 * @param foto - The photos, any order.
 * @returns One per slot.
 */
export function ultimePerChiave(foto: readonly FotoCampione[]): FotoCampione[] {
  const viste = new Set<string>();
  return [...foto]
    .sort((a, b) => b.creata - a.creata)
    .filter((voce) => {
      const chiave = chiaveFoto(voce);
      if (viste.has(chiave)) {
        return false;
      }
      viste.add(chiave);
      return true;
    });
}

/**
 * Each photo's state against the model on screen.
 *
 * @param foto - The gallery.
 * @param modello - The committed rendering's hash; `undefined` while the model is not built yet (no state then).
 * @returns The state by photo id.
 */
export async function statiFoto(
  foto: readonly FotoCampione[],
  modello: string | undefined,
): Promise<ReadonlyMap<string, StatoFoto>> {
  const stati = new Map<string, StatoFoto>();
  if (modello === undefined) {
    return stati;
  }
  for (const voce of foto) {
    // oxlint-disable-next-line no-await-in-loop -- A handful of photos; one digest each.
    const attuale = await improntaFoto({
      modello,
      vista: voce.vista,
      materiale: voce.materiale,
      livello: voce.livello,
    });
    stati.set(voce.id, attuale === voce.impronta ? 'pronta' : 'da-rifare');
  }
  return stati;
}

/**
 * The photo that already answers this fingerprint, if any: the cache that spares a second payment for the same picture.
 *
 * @param foto - The gallery.
 * @param impronta - The fingerprint of the photo about to be asked.
 * @returns The ready photo, or `undefined`.
 */
export const fotoPronta = (foto: readonly FotoCampione[], impronta: string | undefined): FotoCampione | undefined =>
  impronta === undefined ? undefined : foto.find((voce) => voce.impronta === impronta);
